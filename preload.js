const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  getState: () => ipcRenderer.invoke('state:get'),
  setState: patch => ipcRenderer.invoke('state:set', patch),
  onState: fn => ipcRenderer.on('state:changed', (_e, s) => fn(s)),
  search: (src, q) => ipcRenderer.invoke('search', src, q),
  setOnTop: on => ipcRenderer.invoke('widget:onTop', on),
  hideWidget: () => ipcRenderer.invoke('widget:hide'),
  showWidget: () => ipcRenderer.invoke('widget:show'),
  resetWidgetPos: () => ipcRenderer.invoke('widget:resetPos'),
  moveWidget: (x, y) => ipcRenderer.send('widget:move', x, y),
  moveWidgetEnd: () => ipcRenderer.send('widget:moveEnd'),
  setWidgetHit: on => ipcRenderer.send('widget:hit', !!on),
  widgetMenu: () => ipcRenderer.send('widget:menu'),
  openSettings: tab => ipcRenderer.invoke('settings:open', tab),
  onSettingsTab: fn => ipcRenderer.on('settings:tab', (_e, t) => fn(t)),
  getAutostart: () => ipcRenderer.invoke('autostart:get'),
  setAutostart: on => ipcRenderer.invoke('autostart:set', on),
  close: () => ipcRenderer.invoke('win:close'),
  minimize: () => ipcRenderer.invoke('win:minimize'),
  openUrl: url => ipcRenderer.invoke('open:url', url),
  openDataFolder: () => ipcRenderer.invoke('open:data'),
  onWidgetPing: fn => ipcRenderer.on('widget:ping', () => fn()),
  onWidgetQuick: fn => ipcRenderer.on('widget:quick', () => fn()),
  onAchievement: fn => ipcRenderer.on('achievement', (_e, list) => fn(list)),
  onBanner: fn => ipcRenderer.on('widget:banner', (_e, kind, text, sound) => fn(kind, text, sound)),
  setCompact: on => ipcRenderer.invoke('widget:compact', on),
  buyGame: paid => ipcRenderer.invoke('game:buy', paid),
  listBackups: () => ipcRenderer.invoke('backups:list'),
  restoreBackup: file => ipcRenderer.invoke('backups:restore', file),
  backupNow: () => ipcRenderer.invoke('backups:now'),
  refreshPrices: () => ipcRenderer.invoke('prices:refresh'),
  getHotkey: () => ipcRenderer.invoke('hotkey:get'),
  setHotkey: on => ipcRenderer.invoke('hotkey:set', on),
});
